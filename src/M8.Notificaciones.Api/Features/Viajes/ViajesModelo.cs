using Microsoft.EntityFrameworkCore;
using M8.Notificaciones.Api.Features.Viajes.EventStore;
using M8.Notificaciones.Api.Features.Viajes.Proyecciones;

namespace M8.Notificaciones.Api.Features.Viajes;

/// <summary>
/// Configuración EF Core de las tres tablas de la feature Viajes.
/// Está acá (y no dentro de M8DbContext) para que el cambio en el DbContext
/// compartido sea una sola línea y no se mezcle con lo de las otras células.
/// </summary>
public static class ViajesModelo
{
    public static void Configurar(ModelBuilder modelBuilder)
    {
        // ---------------- Lado de escritura: el event store ----------------
        modelBuilder.Entity<EventoAlmacenado>(e =>
        {
            e.ToTable("EventosViaje");
            e.HasKey(x => x.Seq);
            // Npgsql la crea como columna de identidad (GENERATED BY DEFAULT AS IDENTITY).
            e.Property(x => x.Seq).ValueGeneratedOnAdd();
            e.Property(x => x.Tipo).IsRequired().HasMaxLength(50);
            e.Property(x => x.Origen).IsRequired().HasMaxLength(10);
            // Texto y no jsonb: así los tests con EF InMemory se comportan igual.
            e.Property(x => x.Payload).IsRequired();

            // Idempotencia: un mismo eventoId no se guarda dos veces.
            e.HasIndex(x => x.EventoId).IsUnique();
            // Concurrencia optimista: una sola fila por posición del flujo.
            e.HasIndex(x => new { x.ViajeId, x.Version }).IsUnique();
        });

        // ---------------- Lado de lectura: la vista de CQRS ----------------
        modelBuilder.Entity<ViajeHistorialItem>(e =>
        {
            e.ToTable("ViajesHistorialVista");
            // La PK compuesta ES el índice único (ViajeId, Version).
            e.HasKey(x => new { x.ViajeId, x.Version });
            e.Property(x => x.Evento).IsRequired().HasMaxLength(50);
            e.Property(x => x.Descripcion).IsRequired().HasMaxLength(250);
            e.Property(x => x.EstadoResultante).IsRequired().HasMaxLength(20);
        });

        modelBuilder.Entity<ProyeccionCheckpoint>(e =>
        {
            e.ToTable("ProyeccionCheckpoint");
            e.HasKey(x => x.Nombre);
            e.Property(x => x.Nombre).HasMaxLength(100);
        });
    }
}
